// 挨拶 × ベースメッセージ × 語尾 の組み合わせで約5,500個を自動生成
const allMessages = [];

// パターン1: 挨拶単体（おはちくわ！ｗ など）
for (const g of greetings) {
    for (const s of suffixes) {
        allMessages.push(g + s);
    }
}

// パターン2: 挨拶 ＋ ベースメッセージ（こんちくわ！ それな！ など）
for (const g of greetings) {
    for (const b of baseMessages) {
        allMessages.push(`${g} ${b}`);
    }
}

// パターン3: ベースメッセージ ＋ 語尾
for (const b of baseMessages) {
    for (const s of suffixes) {
        allMessages.push(b + s);
    }
}

// パターン4: 強調ワード ＋ ベースメッセージ
const extraWords = ["ガチで", "マジで", "実は", "絶対に", "ここで一句、", "お、"];
for (const e of extraWords) {
    for (const b of baseMessages) {
        allMessages.push(e + b);
    }
}

