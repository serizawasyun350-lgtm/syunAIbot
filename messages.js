const prefixes = [
    'おっ、', 'おーい！', 'おいおい、', 'ねえねえ、', 'ほうほう、',
    'ふむふむ、', 'やっほー！', 'お疲れ！', 'ちょっと聞いてよ、', 'それな！',
    'すごいね！', 'マジで？', 'たしかに！', 'なるほど〜、', 'よっしゃ！'
];

const bodies = [
    'ちくわが美味しすぎて世界が輝いて見える',
    '今日の天気は最高にちくわ日和だな',
    'AIだってたまにはお腹が空くんだぜ',
    'Discordでみんなとおしゃべりするの楽しいな',
    'すんごい秘密を教えてあげようか…？',
    'プログラミングってパズルみたいで面白いよね',
    '夜食に食べた磯辺揚げが最高だった件について',
    'ボットの機能をもっともっと増やしていこうぜ',
    'エラーが出ても諦めずに直すのがエンジニアの魂だ',
    '今日も一日、元気にがんばっていこー',
    'テンション上げていこうぜー',
    'お茶でも飲みながらのんびりやろうよ',
    '今の話、めちゃくちゃ面白いな',
    '突然だけどちくわって穴が空いてて不思議だよね',
    '眠くなってきたけどまだまだいけるぜ'
];

const suffixes = [
    '☆', '！', '…！', 'w', '（笑）', '♪', 'の巻！', 'なのだ！', '✨', '👍', '！w', '…✨'
];

// 起動時に自動で100,000個のセリフを配列に生成
const messages = [];
for (let i = 1; i <= 100000; i++) {
    const p = prefixes[Math.floor(Math.random() * prefixes.length)];
    const b = bodies[Math.floor(Math.random() * bodies.length)];
    const s = suffixes[Math.floor(Math.random() * suffixes.length)];
    messages.push(`${p}${b}${s}`);
}

module.exports = messages;
